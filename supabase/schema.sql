-- Server-authoritative, versioned, idempotent turn commit.
-- The match row lock serializes concurrent submissions for one match. Deduplication is
-- scoped to the match and the submitting user; the expected turn number is re-checked
-- under the lock, so a request computed against an older state can never be written.
-- Returns an outcome instead of raising so the Edge Function can map it to a response.
create or replace function public.commit_match_turn_v2(
  p_match_id uuid,
  p_user_id uuid,
  p_submission_id uuid,
  p_expected_turn_number integer,
  p_actions jsonb,
  p_resulting_state jsonb,
  p_next_current_player text,
  p_next_turn_number integer,
  p_winner text
)
returns table (
  outcome text,
  match_turn_number integer,
  match_current_player text,
  match_winner text,
  match_state jsonb
)
language plpgsql
security definer
set search_path = public
as $$
declare
  match_row public.matches%rowtype;
  seat_side text;
  previous public.turns%rowtype;
begin
  if p_submission_id is null or p_user_id is null or p_expected_turn_number is null then
    raise exception 'submission id, user id, and expected turn number are required.';
  end if;

  select m.*
  into match_row
  from public.matches m
  where m.id = p_match_id
  for update;

  if not found then
    outcome := 'not_found';
    return next;
    return;
  end if;

  select mp.side
  into seat_side
  from public.match_players mp
  where mp.match_id = p_match_id
    and mp.user_id = p_user_id;

  if seat_side is null then
    outcome := 'forbidden';
    return next;
    return;
  end if;

  match_turn_number := match_row.turn_number;
  match_current_player := match_row.current_player;
  match_winner := match_row.winner;
  match_state := match_row.state;

  select t.*
  into previous
  from public.turns t
  where t.match_id = p_match_id
    and t.submission_id = p_submission_id;

  if found then
    if previous.submitted_by is not distinct from p_user_id
      and previous.player_side = seat_side
      and previous.turn_number = p_expected_turn_number
      and previous.actions = p_actions then
      outcome := 'duplicate';
    else
      outcome := 'submission_conflict';
    end if;
    return next;
    return;
  end if;

  if match_row.winner is not null then
    outcome := 'finished';
  elsif match_row.turn_number <> p_expected_turn_number then
    outcome := 'stale';
  elsif match_row.current_player <> seat_side then
    outcome := 'not_your_turn';
  end if;

  if outcome is not null then
    return next;
    return;
  end if;

  if not (
    (p_winner is null and p_next_turn_number = p_expected_turn_number + 1 and p_next_current_player <> seat_side)
    or (p_winner is not null and p_next_turn_number = p_expected_turn_number)
  ) then
    raise exception 'Resulting turn does not follow the expected turn.';
  end if;

  insert into public.turns (
    match_id,
    player_side,
    turn_number,
    actions,
    resulting_state,
    submission_id,
    submitted_by
  )
  values (
    p_match_id,
    seat_side,
    p_expected_turn_number,
    p_actions,
    p_resulting_state,
    p_submission_id,
    p_user_id
  );

  update public.matches m
  set
    current_player = p_next_current_player,
    turn_number = p_next_turn_number,
    winner = p_winner,
    state = p_resulting_state
  where m.id = p_match_id;

  outcome := 'committed';
  match_turn_number := p_next_turn_number;
  match_current_player := p_next_current_player;
  match_winner := p_winner;
  match_state := p_resulting_state;
  return next;
end;
$$;

