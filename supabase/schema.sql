-- Legacy commit used by match-turn deployments that predate commit_match_turn_v2.
-- It has no submission ID or caller-supplied expected version; keep it only until the
-- updated match-turn Edge Function is deployed, then it can be dropped.
create or replace function public.commit_match_turn(
  p_match_id uuid,
  p_player_side text,
  p_turn_number integer,
  p_actions jsonb,
  p_resulting_state jsonb,
  p_next_current_player text,
  p_next_turn_number integer,
  p_winner text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.turns (
    match_id,
    player_side,
    turn_number,
    actions,
    resulting_state
  )
  values (
    p_match_id,
    p_player_side,
    p_turn_number,
    p_actions,
    p_resulting_state
  );

  update public.matches
  set
    current_player = p_next_current_player,
    turn_number = p_next_turn_number,
    winner = p_winner,
    state = p_resulting_state
  where id = p_match_id
    and current_player = p_player_side
    and turn_number = p_turn_number
    and winner is null;

  if not found then
    raise exception 'Match changed before turn commit.';
  end if;
end;
$$;

